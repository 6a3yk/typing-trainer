export function getTypeTitle(typeId) {
  return TASK_TITLES[typeId] ?? `Задание №${typeId}`;
}

export function getSubtypeTitle(typeId, subtypeId, { showDefault = false } = {}) {
  if (subtypeId === "1" && !showDefault) {
    return "";
  }

  return TASK_SUBTITLES[typeId]?.[subtypeId] ?? (subtypeId === "1" ? "Основное" : `Подтип ${subtypeId}`);
}

export function makeTaskTitle(typeId, subtypeTitle = "") {
  const base = `№${typeId}. ${getTypeTitle(typeId)}`;
  return subtypeTitle ? `${base} — ${subtypeTitle}` : base;
}
